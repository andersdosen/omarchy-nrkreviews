// Display names for the Settings → Language picker, each in its own native
// name rather than translated into the current UI language — the same
// convention most language pickers use, so a name is recognizable even to
// someone who can't read whatever language is currently selected. Keep in
// sync with the `languages` keys above (skip the "no" alias — it's just a
// pointer at the nb table, not a separate language).
var languageNames = {
  nb: "Norsk",
  en: "English",
  sv: "Svenska",
  de: "Deutsch",
  da: "Dansk",
  fi: "Suomi",
  es: "Español",
  it: "Italiano"
}

// List for the picker: Norwegian first (the plugin's own default/fallback
// language), then English, then everything else alphabetically by native
// name. "System" is prepended separately by the caller since it isn't a
// real language code.
var pinnedLanguageOrder = ["nb", "en"]

function availableLanguages() {
  var codes = Object.keys(languageNames)
  var pinned = pinnedLanguageOrder.filter(function(code) { return codes.indexOf(code) !== -1 })
  var rest = codes.filter(function(code) { return pinnedLanguageOrder.indexOf(code) === -1 })
    .sort(function(a, b) { return languageNames[a].localeCompare(languageNames[b]) })
  return pinned.concat(rest).map(function(code) {
    return { code: code, name: languageNames[code] }
  })
}

// The system's current language, following Qt.locale() (which reflects the
// desktop/session locale, e.g. LANG) — falls back to "nb" (this plugin's
// default) if the system language has no translation table above.
// Qt.locale().name() can report the deprecated macrolanguage code "no"
// instead of "nb" (Bokmål) depending on how the system locale was set —
// point it at the same table rather than falling back to English.
languages.no = languages.nb

// `override` is the user's Settings → Language choice (a language code) —
// takes precedence over Qt.locale() when it names a known language. Pass
// "" (or leave it out) for the default "System" behavior.
function currentLanguage(override) {
  if (override && languages[override]) return override
  try {
    var name = String(Qt.locale().name || "")
    var lang = name.split("_")[0].toLowerCase()
    return languages[lang] ? lang : "nb"
  } catch (e) {
    return "nb"
  }
}

// Translated string for `key` in `override` (or the system's language when
// override is unset/unknown), falling back to nb, then to the key itself
// if even nb is somehow missing it.
function t(key, override) {
  var table = languages[currentLanguage(override)] || languages.nb
  if (table && table[key] !== undefined) return table[key]
  if (languages.nb && languages.nb[key] !== undefined) return languages.nb[key]
  return key
}
